using System;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.VisualStudio.TestTools.UnitTesting;
using UnitConversion;
using UnitConversion.Base;

namespace UnitConversionTests;

/// <summary>
/// docs/units.md lists every unit of every converter. This test regenerates it and fails if the committed
/// file is stale. To update the file after changing a converter, run the tests with UPDATE_UNITS_DOC=1.
/// </summary>
[TestClass]
public class UnitsDocumentationTests
{
    [TestMethod]
    public void UnitsDocumentIsUpToDate()
    {
        var path = Path.Combine(FindRepositoryRoot(), "docs", "units.md");
        var expected = Generate();

        if (Environment.GetEnvironmentVariable("UPDATE_UNITS_DOC") == "1")
        {
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, expected, new UTF8Encoding(false));
        }

        Assert.IsTrue(File.Exists(path), "docs/units.md is missing. Run the tests with UPDATE_UNITS_DOC=1.");
        Assert.AreEqual(
            expected.ReplaceLineEndings("\n"),
            File.ReadAllText(path).ReplaceLineEndings("\n"),
            "docs/units.md is stale. Run the tests with UPDATE_UNITS_DOC=1 to regenerate it.");
    }

    internal static string Generate()
    {
        var text = new StringBuilder();
        text.AppendLine("# Supported units");
        text.AppendLine();
        text.AppendLine("This file is generated by `UnitsDocumentationTests`. Unit names ignore case. Every row lists all the names a unit answers to.");
        text.AppendLine();

        foreach (var type in ConverterFactory.AllConverterTypes())
        {
            var converter = ConverterFactory.CreateDefault(type);
            var name = type.Name.Replace("Converter", string.Empty, StringComparison.Ordinal);
            text.AppendLine($"## {name}");
            text.AppendLine();

            if (type == typeof(TemperatureConverter))
            {
                text.AppendLine("Temperature scales are converted with formulas rather than a single factor.");
                text.AppendLine();
                text.AppendLine("| Scale | Names |");
                text.AppendLine("|---|---|");
                foreach (var unit in converter.SupportedUnits)
                {
                    text.AppendLine($"| {unit.Synonyms.First()} | {Names(unit)} |");
                }

                text.AppendLine();
                continue;
            }

            text.AppendLine($"Base unit: `{converter.UnitLeft}`. Class: `{type.Name}`.");
            text.AppendLine();
            text.AppendLine("| Unit | Equals (in the base unit) | Names |");
            text.AppendLine("|---|---|---|");
            foreach (var unit in converter.SupportedUnits)
            {
                var first = unit.Synonyms.First();
                text.AppendLine($"| {first} | {ValueInBaseUnit(type, first)} | {Names(unit)} |");
            }

            text.AppendLine();
        }

        return text.ToString().TrimEnd() + "\n";
    }

    private static string Names(UnitFactorSynonyms unit) => string.Join(", ", unit.Synonyms.Select(n => $"`{n}`"));

    private static string ValueInBaseUnit(Type type, string unit)
    {
        var converter = ConverterFactory.CreateDefault(type);
        var baseUnit = converter.UnitLeft;
        converter.UnitLeft = unit;
        converter.UnitRight = baseUnit;
        return converter.LeftToRight(1).ToString("G10", System.Globalization.CultureInfo.InvariantCulture);
    }

    private static string FindRepositoryRoot()
    {
        var directory = new DirectoryInfo(AppContext.BaseDirectory);
        while (directory != null && !File.Exists(Path.Combine(directory.FullName, "UnitConversion.slnx")))
        {
            directory = directory.Parent;
        }

        return directory?.FullName ?? throw new InvalidOperationException("UnitConversion.slnx was not found above the test output.");
    }
}
